def sums(rows_in):
    ok_rows = [r for r in rows_in if not r.get("error")]
    ttfts = [r["ttft_ms"] for r in ok_rows if r.get("ttft_ms") is not None]
    gens = [r["gen_ms"] for r in ok_rows if r.get("gen_ms") is not None]
    walls = [r["elapsed_ms"] for r in ok_rows if r.get("elapsed_ms") is not None]
    rates = [r["tokens_per_sec"] for r in ok_rows if r.get("tokens_per_sec")]
    hits = [r["cache_hit_pct"] for r in ok_rows if r.get("cache_hit_pct") is not None]
    return {"total": len(rows_in), "ok": len(ok_rows),
            "ttft_n": len(ttfts), "ttft_sum": sum(ttfts),
            "gen_n": len(gens), "gen_sum": sum(gens),
            "wall_n": len(walls), "wall_sum": sum(walls),
            "rate_n": len(rates), "hit_n": len(hits)}


