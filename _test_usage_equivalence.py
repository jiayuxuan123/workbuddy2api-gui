def orig_recent_usage(limit=100):
    out_rows, total = [], 0
    with log_open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except Exception:
                continue
            total += 1
            out_rows.append(item)
    return {"total": total, "rows": out_rows[-limit:]}


def orig_usage_by_account():
    buckets = {}
    with log_open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except Exception:
                continue
            if row.get("error"):
                continue
            key = row.get("account") or "(unattributed)"
            bucket = buckets.setdefault(key, {
                "account": key, "requests": 0, "prompt_tokens": 0,
                "completion_tokens": 0, "reasoning_tokens": 0,
                "cached_tokens": 0, "total_tokens": 0, "models": {},
            })
            bucket["requests"] += 1
            for field in ("prompt_tokens", "completion_tokens",
                          "reasoning_tokens", "cached_tokens", "total_tokens"):
                bucket[field] += row.get(field) or 0
            model = row.get("model") or "?"
            bucket["models"][model] = bucket["models"].get(model, 0) + 1
    out = sorted(buckets.values(), key=lambda b: -b["total_tokens"])
    for item in out:
        item["models"] = sorted(item["models"].items(), key=lambda kv: -kv[1])[:5]
    return out


def read_all_rows():
    out = []
    with log_open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                out.append(json.loads(line))
            except Exception:
                continue
    return out


