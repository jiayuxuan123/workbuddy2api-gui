"""Equivalence test: the refactored usage readers must match the originals.

The originals are re-implemented here verbatim from the pre-refactor source
(git baseline 2adaaf5) and run against the same synthetic log as the new
index-backed code. Any divergence in the numbers is a regression.

The synthetic rows come from a small deterministic generator rather than the
``random`` module: a regression test must produce the same data on every run,
so a failure can always be reproduced.

All file access goes through ``log_open()``, which resolves the path and
proves it stays inside the temp directory this test created. The path is
generated by ``tempfile`` in the first place, but keeping the containment
check explicit means the test can only ever touch its own fixture.
"""
