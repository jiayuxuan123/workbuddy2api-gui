TOKEN_FIELDS = ("prompt_tokens", "completion_tokens", "reasoning_tokens",
                "cached_tokens", "total_tokens", "credit")


def orig_totals(realm, all_rows):
    """Reference implementation of the pre-refactor usage_snapshot() loop.

    Copied from baseline 2adaaf5: each model bucket carries `requests`, an
    `accounts` map of per-account request counts, and the token fields.
    """
    tot = {"requests": 0, "errors": 0}
    for f in TOKEN_FIELDS:
        tot[f] = 0
    by_model = {}
    for r in all_rows:
        row_realm = r.get("realm")
        if not row_realm:
            row_realm = "intl"       # resolver semantics for legacy rows
        if row_realm != realm:
            continue
        if r.get("error"):
            tot["errors"] += 1
            continue
        tot["requests"] += 1
        for f in TOKEN_FIELDS:
            if f in r:
                tot[f] += (r[f] or 0)
        m = r.get("model") or "unknown"
        per = by_model.setdefault(
            m, {"requests": 0, "accounts": {}, **{k: 0 for k in TOKEN_FIELDS}})
        per["requests"] += 1
        for f in TOKEN_FIELDS:
            if f in r:
                per[f] += (r[f] or 0)
        acct_id = r.get("account")
        if acct_id:
            per["accounts"][acct_id] = per["accounts"].get(acct_id, 0) + 1
    return tot, by_model


