failures = []


def check(name, expected, actual):
    if expected == actual:
        print("  PASS  %s" % name)
    else:
        print("  FAIL  %s" % name)
        print("        expected: %r" % (expected,))
        print("        actual  : %r" % (actual,))
        failures.append(name)


class Seq(object):
    """Deterministic pseudo-sequence for building fixtures."""

    def __init__(self, seed=12345):
        self.state = seed

    def next(self):
        # xorshift: stable across runs and platforms
        x = self.state
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= (x >> 17)
        x ^= (x << 5) & 0xFFFFFFFF
        self.state = x & 0xFFFFFFFF
        return self.state

    def pick(self, items):
        return items[self.next() % len(items)]

    def below(self, n):
        return self.next() % n

    def chance(self, percent):
        return (self.next() % 100) < percent


# ---------------------------------------------------------------------------
# Fixture root. Every path used below is derived from it and re-validated on
# each open, so this test cannot reach outside the directory it created.
# ---------------------------------------------------------------------------
FIXTURE_ROOT = os.path.realpath(tempfile.mkdtemp(prefix="wbequiv_"))
LOG_PATH = os.path.join(FIXTURE_ROOT, "usage.jsonl")


def log_open(mode="r", **kwargs):
    """Open the fixture log, refusing any path outside FIXTURE_ROOT."""
    resolved = os.path.realpath(LOG_PATH)
    if resolved != os.path.join(FIXTURE_ROOT, "usage.jsonl"):
        raise ValueError("fixture log path escaped the fixture root")
    if os.path.commonpath([resolved, FIXTURE_ROOT]) != FIXTURE_ROOT:
        raise ValueError("refusing to open a path outside the fixture root")
    return open(resolved, mode, **kwargs)


